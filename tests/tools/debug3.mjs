import { launchWithExtension, FIXTURE_URL, EXT_ID } from './helpers.ts';
const { context, sw } = await launchWithExtension();
const page = await context.newPage();
await page.goto(FIXTURE_URL);
await page.waitForSelector('.msg-row');
const panel = await context.newPage();
await panel.goto(`chrome-extension://${EXT_ID}/sidepanel.html`);
await panel.waitForSelector('#req');
await panel.fill('#req', 'x');
await panel.click('#gen-btn');
await panel.waitForSelector('.card h3');
await panel.click('button.primary:has-text("Approve & Run")');
await page.waitForSelector('.gj-toolbar div[id^="wwa-"]', { timeout: 15000 });
await page.locator('.gj-toolbar div[id^="wwa-"] >> css=button').click();
await page.waitForFunction(() => window.__drafts?.length === 2, undefined, { timeout: 60000 });
await page.waitForTimeout(2500);
console.log('PANEL TEXT:', (await panel.evaluate(() => document.body.innerText)).replace(/\n/g,' | ').slice(0, 900));
console.log('SW widgets:', await sw.evaluate(async () => JSON.stringify((await chrome.storage.local.get('wwa_widgets')).wwa_widgets?.map(w => ({id: w.id, status: w.status})))));
await context.close();
